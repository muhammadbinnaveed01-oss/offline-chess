/**
 * Convert a square like 'e4' into an 8x8 index (0 to 63)
 * Rank 8 is row 0, rank 1 is row 7. File a is col 0, file h is col 7.
 */
export function squareToIndex(square: string): number {
  const file = square.charCodeAt(0) - 97; // 'a' -> 0
  const rank = 8 - parseInt(square[1], 10); // '8' -> 0, '1' -> 7
  return rank * 8 + file;
}

/**
 * Get the positional table value for a piece on a given square
 */
export function getPieceSquareValue(
  pieceType: PieceType,
  color: 'w' | 'b',
  square: string,
  isEndgame = false
): number {
  let index = squareToIndex(square);
  // For Black pieces, mirror the table vertically
  if (color === 'b') {
    const row = Math.floor(index / 8);
    const col = index % 8;
    index = (7 - row) * 8 + col;
  }

  switch (pieceType) {
    case 'p':
      return PAWN_PST[index];
    case 'n':
      return KNIGHT_PST[index];
    case 'b':
      return BISHOP_PST[index];
    case 'r':
      return ROOK_PST[index];
    case 'q':
      return QUEEN_PST[index];
    case 'k':
      return isEndgame ? KING_ENDGAME_PST[index] : KING_MIDGAME_PST[index];
    default:
      return 0;
  }
}
